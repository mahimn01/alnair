#!/usr/bin/env python3
"""research_tool: the command line for the clp-research toolkit (also what the Claude Code plugin runs).

What it does: runs one research tool (scholarly search, SEC, patents, Wayback, GitHub, any public
page, plus lookup/read/verify over everything saved) and prints a compact answer. Every fetched
source is saved as exact text under ~/.clp/research so you can quote it with an address + hash.
Why: lets Claude (and you) research with sources that can be re-checked later.

How to run:
    research_tool.py list                              the tools
    research_tool.py status [--live] [--deep]          doctor: store, index, provider capabilities
    research_tool.py scholar_search "attention is all you need" --source openalex --limit 3
    research_tool.py sec_filings AAPL --form 10-K
    research_tool.py research_lookup "revenue growth"
    research_tool.py call TOOL < args.json             JSON object of arguments on stdin (what the plugin uses)
    research_tool.py manifest                          print the JS tool table (used to regenerate the plugin file)
Exit codes: 0 ok, 1 verify refused, 2 error, 3 provider UNAVAILABLE (reported honestly), 4 disabled.

What it changes: writes only under $RESEARCH_HOME (default ~/.clp/research): saved sources, an HTTP cache
(size-capped) and the CLP index. Network: public reads only; no API keys, no logins except the gh CLI session.
Turn it off with CLAUDE_RESEARCH_DISABLE=1.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from clpresearch import tools  # noqa: E402


def parse_cli(argv: list[str]) -> tuple[str, dict]:
    name, rest = argv[0], argv[1:]
    name = {"status": "research_status", "lookup": "research_lookup", "read": "research_read", "verify": "research_verify", "sources": "research_sources", "fetch": "research_fetch"}.get(name, name)
    tool = tools.BY_NAME.get(name)
    if tool is None:
        raise SystemExit(f"unknown tool {name!r}; run `research_tool.py list`")
    args: dict = {}
    positional = [r for r in tool.required]
    i = 0
    while i < len(rest):
        tok = rest[i]
        if tok.startswith("--"):
            key = tok[2:].replace("-", "_")
            spec = tool.props.get(key)
            if spec is None:
                raise SystemExit(f"unknown option {tok} for {name}; options: {', '.join('--' + p for p in tool.props)}")
            if spec["type"] == "boolean":
                nxt = rest[i + 1] if i + 1 < len(rest) else ""
                if nxt in ("true", "false"):
                    args[key], i = nxt == "true", i + 2
                else:
                    args[key], i = True, i + 1
            else:
                if i + 1 >= len(rest):
                    raise SystemExit(f"{tok} needs a value")
                args[key], i = rest[i + 1], i + 2
        else:
            if not positional:
                raise SystemExit(f"unexpected argument {tok!r}")
            args[positional.pop(0)] = tok
            i += 1
    return name, args


def main(argv: list[str]) -> int:
    if not argv or argv[0] in ("-h", "--help", "help"):
        print(__doc__)
        return 0
    if argv[0] == "list":
        for t in tools.TOOLS:
            print(f"{t.name:18} {t.description.split('. ')[0][:110]}")
        return 0
    if argv[0] == "manifest":
        sys.stdout.write(manifest_js())
        return 0
    if argv[0] == "call":
        if len(argv) < 2:
            raise SystemExit("usage: research_tool.py call TOOL < json")
        try:
            args = json.loads(sys.stdin.read() or "{}")
        except ValueError:
            print("ERROR: stdin is not valid JSON")
            return 2
        if not isinstance(args, dict):
            print("ERROR: arguments must be a JSON object")
            return 2
        name = argv[1]
    else:
        name, args = parse_cli(argv)
    code, text = tools.run(name, args)
    print(text)
    return code


FORMAT = {"type": "string", "enum": ["text", "json"], "description": "text (default) or json: the result is one JSON object {tool, ok, status, exitCode, text, refs} returned as text"}


def manifest_js() -> str:
    """The generated plugin/hooks/tools.generated.js (kept in sync by a test)."""
    items = []
    for t in tools.TOOLS:
        items.append({"name": t.name, "isDeferred": t.deferred, "timeoutMs": t.timeout_ms, "description": t.description + ' format:"json" returns a JSON object as text.',
                      "inputSchema": {"type": "object", "properties": {**t.props, "format": FORMAT}, "required": t.required, "additionalProperties": False}, **({"stdinKey": t.stdin_key} if t.stdin_key else {})})
    return ("// GENERATED by `research_tool.py manifest` from clpresearch/tools.py. Do not edit; a test checks it is current.\n"
            "export const TOOLS = " + json.dumps(items, indent=1, ensure_ascii=False) + ";\n")


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
